"""Markdown report generator."""

from __future__ import annotations

from datetime import datetime
from pathlib import Path

try:
    from rich.console import Console
    console = Console()
except ImportError:
    class DummyConsole:
        def print(self, *args, **kwargs):
            import re
            import sys
            text = " ".join(str(a) for a in args)
            clean_text = re.sub(r"\[/?[\w\s=#]+\]", "", text)
            try:
                print(clean_text)
            except UnicodeEncodeError:
                safe_text = clean_text.encode(sys.stdout.encoding or "utf-8", errors="replace").decode(sys.stdout.encoding or "utf-8")
                print(safe_text)
    console = DummyConsole()


def generate_report(
    title: str,
    content: str,
    filepath: str | None = None,
    metadata: dict | None = None,
) -> str:
    """Generate a Markdown report.

    Args:
        title: Report title.
        content: Main report content (Markdown formatted).
        filepath: Reviewed file path.
        metadata: Additional metadata to include.

    Returns:
        Complete Markdown report as a string.
    """
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    report_parts = [
        f"# {title}\n",
        f"**Generated:** {now}  ",
    ]

    if filepath:
        report_parts.append(f"**File:** `{filepath}`  ")

    if metadata:
        for key, value in metadata.items():
            report_parts.append(f"**{key}:** {value}  ")

    report_parts.append("\n---\n")
    report_parts.append(content)
    report_parts.append("\n\n---\n")
    report_parts.append(
        f"*Generated by [Local CodeReview AI](https://github.com/YOUR_USERNAME/local-codereview-ai) "
        f"at {now}*\n"
    )

    return "\n".join(report_parts)


def save_report(report: str, output_path: str) -> None:
    """Save a report to a file.

    Args:
        report: Report content.
        output_path: Path to save the report.
    """
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(report, encoding="utf-8")
    console.print(f"\n[green]✅ Report saved to: {output_path}[/green]")
